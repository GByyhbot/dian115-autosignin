# -*- coding: utf-8 -*-
"""从 PT-depiler definitions 抽取 NexusPHP 站点，生成 core/presets_extra.go。
筛选：NexusPHP 框架、https 可用、排除校内教育网、排除现有 22 大站、域名去重。
"""
import json, re, os

SRC = r'D:\dian115-SL\.tools\ptd_sites.json'
OUT = r'D:\dian115-SL\dian115-autosignin\core\presets_extra.go'

# 现有 22 大站 key（专用处理器或已内置），不重复生成
EXISTING = {
    '52pt', 'btschool', 'chdbits', 'haidan', 'hares', 'hdarea', 'hdchina',
    'hdcity', 'hdsky', 'hdupt', 'mteam', 'nexushd', 'opencd', 'pterclub',
    'pttime', 'ptzone', 'rousi', 'tjupt', 'ttg', 'u2', 'yema', 'zhuque',
}
# ptd id 与现有 key 的别名映射（同一站点）
ALIAS_EXISTING = {'pter': 'pterclub'}

def host_of(url):
    m = re.match(r'https?://([^/]+)/?', url)
    if not m:
        return ''
    h = m.group(1).lower()
    if h.startswith('www.'):
        h = h[4:]
    return h

sites = json.load(open(SRC, encoding='utf-8'))
picked = []
seen_host = set()
skipped = {'existing': 0, 'edu': 0, 'nourl': 0, 'dup': 0}

for s in sites:
    if s['schema'] != 'NexusPHP':
        continue
    sid = s['id']
    if sid in EXISTING or sid in ALIAS_EXISTING:
        skipped['existing'] += 1
        continue
    urls = [u for u in s['urls'] if u.startswith('https://')]
    if not urls:
        skipped['nourl'] += 1
        continue
    homepage = urls[0]
    host = host_of(homepage)
    if '.edu.cn' in host or 'edu.' in host:
        skipped['edu'] += 1
        continue
    if host in seen_host:
        skipped['dup'] += 1
        continue
    name = (s['name'] or '').strip() or sid
    seen_host.add(host)
    picked.append({'key': sid, 'name': name, 'host': host, 'homepage': homepage})

def go_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

lines = []
lines.append('package core')
lines.append('')
lines.append('// Code generated by scripts/generate_presets.py from PT-depiler NexusPHP definitions. DO NOT EDIT.')
lines.append('// 来源: https://github.com/pt-plugins/PT-depiler (MIT)；仅取站点目录元数据（名称/域名），')
lines.append('// 签到走通用 NexusPHP attendance.php 流程；Unit3D/Gazelle 等无签到框架不纳入。')
lines.append('')
lines.append('// ExtraNexusPresets NexusPHP 小站预设（通用签到处理器）。')
lines.append('var ExtraNexusPresets = []SitePreset{')
for p in picked:
    name = p['name'].replace('"', '\\"')
    lines.append('\t{Key: %s, Name: %s, Domain: %s, Framework: "nexusphp", Homepage: %s},' % (
        go_str(p['key']), go_str(name), go_str(p['host']), go_str(p['homepage'])))
lines.append('}')
lines.append('')

open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('picked:', len(picked))
print('skipped:', skipped)
print('written:', OUT)
